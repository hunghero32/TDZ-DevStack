function Update-VirtualHosts {
    param([string]$RootDir)
    
    $config = Get-TDZConfig -RootDir $RootDir
    $wwwDir = Join-Path $RootDir "www"
    $sitesDir = Join-Path $RootDir "etc\apache2\sites-enabled"
    $tld = $config.preferences.tld
    $hostsFile = "C:\Windows\System32\drivers\etc\hosts"
    
    if (-not (Test-Path $sitesDir)) { New-Item -ItemType Directory -Path $sitesDir -Force | Out-Null }
    if (-not (Test-Path $wwwDir)) { return @{ success = $true; message = "No www directory" } }
    
    $projects = Get-ChildItem $wwwDir -Directory -ErrorAction SilentlyContinue
    $hostsEntries = @()
    $created = 0
    
    foreach ($project in $projects) {
        $projectName = $project.Name
        $domain = "$projectName$tld"
        $confFile = Join-Path $sitesDir "auto.$domain.conf"
        
        # Determine document root (check for public/ subdirectory)
        $docRoot = $project.FullName
        if (Test-Path (Join-Path $docRoot "public")) { $docRoot = Join-Path $docRoot "public" }
        $docRootUnix = $docRoot -replace '\\', '/'
        
        # Create Apache vhost config
        if (-not (Test-Path $confFile)) {
            $port = $config.services.apache.port
            $vhostContent = @"
# Auto-generated by TDZ DevStack for: $projectName
<VirtualHost *:$port>
    DocumentRoot "$docRootUnix"
    ServerName $domain
    ServerAlias *.$domain
    <Directory "$docRootUnix">
        AllowOverride All
        Require all granted
    </Directory>
</VirtualHost>
"@
            Set-Content -Path $confFile -Value $vhostContent -Force
            $created++
            Write-TDZLog -RootDir $RootDir -Service "vhost" -Message "Created vhost: $domain -> $docRootUnix"
        }
        
        $hostsEntries += "127.0.0.1`t$domain"
    }
    
    # Generate Nginx vhost configs too
    $nginxSitesDir = Join-Path $RootDir "etc\nginx\sites-enabled"
    if (Test-Path (Split-Path $nginxSitesDir)) {
        if (-not (Test-Path $nginxSitesDir)) { New-Item -ItemType Directory -Path $nginxSitesDir -Force | Out-Null }
        foreach ($project in $projects) {
            $projectName = $project.Name
            $domain = "$projectName$tld"
            $confFile = Join-Path $nginxSitesDir "auto.$domain.conf"
            
            $docRoot = $project.FullName
            if (Test-Path (Join-Path $docRoot "public")) { $docRoot = Join-Path $docRoot "public" }
            $docRootUnix = $docRoot -replace '\\', '/'
            
            if (-not (Test-Path $confFile)) {
                $nginxPort = $config.services.nginx.port
                $nginxConf = @'
# Auto-generated by TDZ DevStack
server {
    listen __PORT__;
    server_name __DOMAIN__ *.__DOMAIN__;
    root "__DOCROOT__";
    index index.php index.html;

    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    location ~ \.php$ {
        fastcgi_pass 127.0.0.1:2004;
        fastcgi_index index.php;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        include fastcgi_params;
    }
}
'@
                $nginxConf = $nginxConf -replace '__PORT__', $nginxPort -replace '__DOMAIN__', $domain -replace '__DOCROOT__', $docRootUnix
                Set-Content -Path $confFile -Value $nginxConf -Force
            }
        }
    }
    
    # Update Windows hosts file
    try {
        $hostsContent = Get-Content $hostsFile -Raw -ErrorAction Stop
        $changed = $false
        foreach ($entry in $hostsEntries) {
            $domain = ($entry -split "`t")[1]
            if ($hostsContent -notmatch [regex]::Escape($domain)) {
                $hostsContent += "`n$entry"
                $changed = $true
            }
        }
        if ($changed) {
            Set-Content -Path $hostsFile -Value $hostsContent -Force -ErrorAction Stop
            Write-TDZLog -RootDir $RootDir -Service "vhost" -Message "Updated hosts file with $($hostsEntries.Count) entries"
        }
        return @{ success = $true; message = "Virtual hosts updated ($created new configs)" }
    } catch {
        return @{ success = $true; message = "VHost configs updated ($created new). Hosts file requires admin rights." }
    }
}

function Get-VirtualHosts {
    param([string]$RootDir)
    
    $config = Get-TDZConfig -RootDir $RootDir
    $sitesDir = Join-Path $RootDir "etc\apache2\sites-enabled"
    $tld = $config.preferences.tld
    $vhosts = @()
    
    if (Test-Path $sitesDir) {
        Get-ChildItem $sitesDir -Filter "*.conf" -ErrorAction SilentlyContinue | ForEach-Object {
            $content = Get-Content $_.FullName -Raw
            $domain = if ($content -match 'ServerName\s+(\S+)') { $matches[1] } else { $_.BaseName }
            $docRoot = if ($content -match 'DocumentRoot\s+"([^"]+)"') { $matches[1] } else { "" }
            $vhosts += @{
                file = $_.Name
                domain = $domain
                docRoot = $docRoot
                autoGenerated = $_.Name -like "auto.*"
            }
        }
    }
    
    return $vhosts
}

function Remove-VirtualHost {
    param(
        [string]$Domain,
        [string]$RootDir
    )
    
    $sitesDir = Join-Path $RootDir "etc\apache2\sites-enabled"
    $confFile = Join-Path $sitesDir "auto.$Domain.conf"
    
    if (Test-Path $confFile) {
        Remove-Item $confFile -Force
        Write-TDZLog -RootDir $RootDir -Service "vhost" -Message "Removed vhost: $Domain"
        return @{ success = $true; message = "Virtual host '$Domain' removed" }
    }
    
    return @{ success = $false; message = "Virtual host config not found for '$Domain'" }
}
