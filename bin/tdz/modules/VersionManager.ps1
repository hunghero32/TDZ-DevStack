# ============================================================
# TDZ DevStack - VersionManager Module
# Version switching for services and runtimes
# ============================================================

function Switch-ServiceVersion {
    param(
        [string]$ServiceName,
        [string]$NewVersion,
        [string]$RootDir
    )
    
    $config = Get-TDZConfig -RootDir $RootDir
    $meta = Get-ServiceMeta -RootDir $RootDir
    $svc = $meta[$ServiceName]
    
    if (-not $svc) { return @{ success = $false; message = "Unknown service: $ServiceName" } }
    if ($NewVersion -notin $svc.versions) { return @{ success = $false; message = "Version '$NewVersion' not available for $($svc.name). Available: $($svc.versions -join ', ')" } }
    
    Write-TDZLog -RootDir $RootDir -Service $ServiceName -Message "Switching $($svc.name) from $($svc.active) to $NewVersion"
    
    # Update config
    $configPath = if ($svc.isRuntime) { "runtimes.$ServiceName.active" } else { "services.$ServiceName.active" }
    Update-ConfigValue -RootDir $RootDir -Path $configPath -Value $NewVersion
    
    # Special handling for PHP: update Apache mod_php config
    if ($ServiceName -eq "php") {
        Update-PhpApacheConfig -RootDir $RootDir -PhpVersion $NewVersion
        
        # Restart Apache if running
        $apacheStatus = Get-ProcessStatus -ProcessName "httpd"
        if ($apacheStatus.running) {
            Restart-TDZService -ServiceName "apache" -RootDir $RootDir | Out-Null
        }
    }
    
    # For services (not runtimes): restart if running
    if (-not $svc.isRuntime -and $svc.processName) {
        $status = Get-ProcessStatus -ProcessName $svc.processName
        if ($status.running) {
            Stop-TDZService -ServiceName $ServiceName -RootDir $RootDir | Out-Null
            Start-Sleep -Milliseconds 500
            Start-TDZService -ServiceName $ServiceName -RootDir $RootDir | Out-Null
        }
    }
    
    Write-TDZLog -RootDir $RootDir -Service $ServiceName -Message "$($svc.name) switched to $NewVersion successfully"
    return @{ success = $true; message = "$($svc.name) switched to $NewVersion" }
}

function Update-PhpApacheConfig {
    param(
        [string]$RootDir,
        [string]$PhpVersion
    )
    
    $modPhpConf = Join-Path $RootDir "etc\apache2\mod_php.conf"
    $binDir = Join-Path $RootDir "bin"
    $rootUnix = $RootDir -replace '\\', '/'
    
    # Detect PHP major version for module name
    $phpMajor = if ($PhpVersion -match "php-(\d+)") { $matches[1] } else { "8" }
    
    # Check if TS (Thread Safe) or NTS
    $isNTS = $PhpVersion -match "nts"
    
    if ($isNTS) {
        # NTS uses php-cgi (FastCGI) not mod_php
        $fcgiConf = Join-Path $RootDir "etc\apache2\fcgid.conf"
        if (Test-Path $fcgiConf) {
            $content = Get-Content $fcgiConf -Raw
            $content = $content -replace 'FcgidInitialEnv PHPRC "[^"]*"', "FcgidInitialEnv PHPRC `"$rootUnix/bin/php/$PhpVersion`""
            $content = $content -replace 'FcgidWrapper "[^"]*"', "FcgidWrapper `"$rootUnix/bin/php/$PhpVersion/php-cgi.exe`""
            Set-Content -Path $fcgiConf -Value $content -Force
        }
    } else {
        # Thread Safe uses mod_php
        if (Test-Path $modPhpConf) {
            $newContent = @"
# Auto-generated by TDZ DevStack - DO NOT EDIT MANUALLY
LoadModule php_module "$rootUnix/bin/php/$PhpVersion/php${phpMajor}apache2_4.dll"
PHPIniDir "$rootUnix/bin/php/$PhpVersion"
<IfModule mime_module>
    AddType application/x-httpd-php .php
</IfModule>
"@
            Set-Content -Path $modPhpConf -Value $newContent -Force
        }
    }
}

function Get-AvailableVersions {
    param(
        [string]$ServiceName,
        [string]$RootDir
    )
    
    $meta = Get-ServiceMeta -RootDir $RootDir
    $svc = $meta[$ServiceName]
    
    if (-not $svc) { return @() }
    
    return @{
        service   = $ServiceName
        name      = $svc.name
        active    = $svc.active
        installed = $svc.versions
    }
}

function Get-AllVersionInfo {
    param([string]$RootDir)
    
    $meta = Get-ServiceMeta -RootDir $RootDir
    $result = @{}
    
    foreach ($key in $meta.Keys) {
        $svc = $meta[$key]
        $result[$key] = @{
            name      = $svc.name
            active    = $svc.active
            versions  = $svc.versions
            isRuntime = [bool]$svc.isRuntime
        }
    }
    
    return $result
}
